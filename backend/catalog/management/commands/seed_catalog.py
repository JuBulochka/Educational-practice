class Command(BaseCommand):
    help = "Добавить учебные категории, услуги и восемь демонстрационных заявок."

    @transaction.atomic
    def handle(self, *args, **options):
        services = []
        for category_name, slug, entries in CATALOG:
            category, _ = Category.objects.get_or_create(slug=slug, defaults={"name": category_name})
            for name, description, price, duration, available in entries:
                service, _ = Service.objects.get_or_create(
                    category=category,
                    name=name,
                    defaults={
                        "description": description,
                        "price": price,
                        "duration_minutes": duration,
                        "is_available": available,
                    },
                )
                if service.is_available:
                    services.append(service)
        for index, service in enumerate(services[:8], start=1):
            ServiceRequest.objects.get_or_create(
                service=service,
                client_name=f"Учебный клиент {index}",
                phone=f"+700000000{index:02}",
                defaults={"desired_at": timezone.now() + timedelta(days=index)},
            )
        self.stdout.write(self.style.SUCCESS("Демонстрационные данные добавлены."))
